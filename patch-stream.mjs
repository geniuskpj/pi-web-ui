import fs from "node:fs";
let s = fs.readFileSync("server.mjs", "utf8");
const start = s.indexOf('app.post("/api/exec/tool", async (c) => {');
const marker = "\t}\n});";
const si = s.indexOf(marker, start);
if (start < 0 || si < 0) { console.error("anchors not found", start, si); process.exit(1); }
const end = si + marker.length;
const L = [
'app.post("/api/exec/tool", async (c) => {',
"\t// ALWAYS token-required — even loopback. A drive-by web page can send simple",
"\t// cross-origin POSTs (no preflight for text/plain) and read nothing back, but",
"\t// execution would still happen server-side; the token header is unforgable",
"\t// cross-origin, which closes that hole. Tool defs (GET) stay loopback-friendly.",
'\tif (!tokenMatches(c.env?.incoming)) {',
'\t\treturn c.json({ error: "unauthorized — tool execution needs x-pi-web-token (see data/auth-token.txt)" }, 401);',
"\t}",
'\tconst body = await c.req.json().catch(() => ({}));',
'\tconst name = String(body?.tool || "");',
"\t// param coercion (GLM shapes): JSON-string params, null, arrays → object",
"\tlet toolParams = body?.params;",
'\tif (typeof toolParams === "string") { try { toolParams = JSON.parse(toolParams); } catch { toolParams = { value: toolParams }; } }',
'\tif (!toolParams || typeof toolParams !== "object" || Array.isArray(toolParams)) toolParams = toolParams ? { value: toolParams } : {};',
'\tconst allow = (process.env.PI_WEB_TOOLS || "").split(",").map((s) => s.trim()).filter(Boolean);',
"\tconst tool = [...builtinTools, ...extensionTools].find((t) => t.name === name);",
'\tif (!tool || (allow.length && !allow.includes(name))) return c.json({ content: [{ type: "text", text: `unknown or disallowed tool: ${name}` }] }, 404);',
"\t// audit trail for the highest-trust surface in the stack (sonnet review):",
"\t// timestamp, tool, trimmed params — outcome amended after execution; surfaced",
"\t// via /api/debug/state",
"\tconst t0 = Date.now();",
'\tconst auditEntry = { at: new Date().toISOString(), tool: name, params: JSON.stringify(toolParams).slice(0, 300), outcome: null };',
"\texecAudit.push(auditEntry);",
"\tif (execAudit.length > 50) execAudit.shift();",
"\tconst finishAudit = (outcome) => { auditEntry.outcome = { isError: !!outcome?.isError, exitCode: outcome?.details?.exitCode, error: outcome?.error, ms: Date.now() - t0 }; };",
'\t// STREAMING: bash pushes partial snapshots via onUpdate → NDJSON frames',
	// {type:"partial"}; final frame {type:"result"}; 15s heartbeat so proxies do not
"\t// idle-kill a quiet build. Client disconnect aborts the tool (taskkill).",
'\tif (body?.stream && name === "bash") {',
"\t\tconst encoder = new TextEncoder();",
"\t\tconst abortCtrl = new AbortController();",
'\t\tconst onClientGone = () => abortCtrl.abort(new Error("client disconnected"));',
'\t\tc.env?.incoming?.once("close", onClientGone);',
"\t\tlet closed = false;",
"\t\tconst stream = new ReadableStream({",
"\t\t\tasync start(controller) {",
'\t\t\t\tconst send = (obj) => { if (closed) return; try { controller.enqueue(encoder.encode(JSON.stringify(obj) + "\\n")); } catch { closed = true; } };',
'\t\t\t\tconst heartbeat = setInterval(() => send({ type: "ping", at: Date.now() }), 15000);',
'\t\t\t\tconst onUpdate = (partialResult) => send({ type: "partial", partialResult });',
"\t\t\t\tconst sig = AbortSignal.any([AbortSignal.timeout(120000), abortCtrl.signal]);",
"\t\t\t\ttry {",
"\t\t\t\t\tconst result = await tool.execute(crypto.randomUUID(), toolParams, sig, onUpdate);",
"\t\t\t\t\tfinishAudit(result);",
'\t\t\t\t\tsend({ type: "result", result: normalizeToolResult(result) });',
"\t\t\t\t} catch (err) {",
"\t\t\t\t\tfinishAudit({ isError: true, error: String(err?.message || err) });",
'\t\t\t\t\tsend({ type: "result", result: { isError: true, content: [{ type: "text", text: `Error: ${err?.message || err}` }] } });',
"\t\t\t\t} finally {",
"\t\t\t\t\tclearInterval(heartbeat);",
'\t\t\t\t\tc.env?.incoming?.removeListener("close", onClientGone);',
"\t\t\t\t\tclosed = true;",
"\t\t\t\t\ttry { controller.close(); } catch { /* already closed */ }",
"\t\t\t\t}",
"\t\t\t},",
"\t\t});",
'\t\treturn c.new Response(stream, { headers: { "content-type": "application/x-ndjson", "cache-control": "no-cache", "x-accel-buffering": "no" } });',
"\t}",
"\ttry {",
"\t\tconst result = await tool.execute(crypto.randomUUID(), toolParams, AbortSignal.timeout(120000));",
"\t\tfinishAudit(result);",
'\t\treturn c.json(normalizeToolResult(result), 200, { "Cache-Control": "no-cache" });',
"\t} catch (err) {",
"\t\tfinishAudit({ isError: true, error: String(err?.message || err) });",
"\t\t// tool errors go back to the MODEL as tool output (200) with isError — the loop's",
"\t\t// retry framing needs it, and a bare success would read as 'edit worked'",
'\t\treturn c.json({ isError: true, content: [{ type: "text", text: `Error: ${err?.message || err}` }] });',
"\t}",
"});",
];
s = s.slice(0, start) + L.join("\n") + s.slice(end);
fs.writeFileSync("server.mjs", s);
console.log("streaming bridge installed");
